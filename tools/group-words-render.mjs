/*
 * group-words-render.mjs — tools/group-words.mjs, the words the port-group inference (tools/group-infer.mjs) speaks and
 * reads, rendered from their owners' domains so group-infer stays a module a browser loads as it is (%4): the verdict's
 * outcomes and reasons (the panel domain's PANEL_GROUP_OUTCOMES, PANEL_GROUP_REASONS, sorting pass V2) and the standard
 * meaning of each LV2 designation (plugin-db's F1 mapping, its lv2 domain's LV2_DESIGNATION_MEANINGS, P3), each by title.
 * Neither is typed by hand; a render that differs from the committed file is red (--check, the test).
 *
 *   node tools/group-words-render.mjs                     write tools/group-words.mjs
 *   node tools/group-words-render.mjs --check             exit 1 when tools/group-words.mjs is not what the domains give
 *   node tools/group-words-render.mjs ... --contract-dir <d>  read <d> first (a `:` list), before the domains' homes
 *
 * The panel domain is opened where the tools open it ($OMX_CONTRACT_PATH, this tree's contract.d, the installed one),
 * plugin-db's lv2 domain from the contract directories plugin-db-contract installs into.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { openDomainAt } from '@openmixer/omx-contract/domain-reader';
import { isMain } from '@openmixer/omx-contract/entry';
import { contractDirs, panelDomainDirs } from './vocabulary.mjs';

export const OUT_FILE = join(dirname(fileURLToPath(import.meta.url)), 'group-words.mjs');

const byTitle = (words) => Object.fromEntries(words.map((w) => [w.title, w.word]));
const object = (o) => `Object.freeze({\n${Object.entries(o).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n')}\n})`;

/** The text of tools/group-words.mjs for the domains found first in `extra` (directories), then in their homes. */
export function groupWordsText(extra = []) {
  const panel = openDomainAt([...extra, ...panelDomainDirs()], 'panel');
  const lv2 = openDomainAt([...extra, ...contractDirs()], 'lv2');
  return `// SPDX-License-Identifier: GPL-3.0-or-later
// Copyright (C) 2026 Pau Aliagas <linuxnow@gmail.com>
// GENERATED by tools/group-words-render.mjs: DO NOT EDIT BY HAND. The port-group inference's words, by title, from the
// panel domain (PANEL_GROUP_OUTCOMES, PANEL_GROUP_REASONS) and plugin-db's lv2 domain (LV2_DESIGNATION_MEANINGS, F1).

/** The verdict's outcomes: PANEL_GROUP_OUTCOMES. */
export const GROUP_OUTCOMES = ${object(byTitle(panel.words('PANEL_GROUP_OUTCOMES')))};

/** The verdict's reasons: PANEL_GROUP_REASONS. */
export const GROUP_REASONS = ${object(byTitle(panel.words('PANEL_GROUP_REASONS')))};

/** The standard meaning of each LV2 designation term plugin-db's F1 maps: LV2_DESIGNATION_MEANINGS. */
export const DESIGNATION_MEANINGS = ${object(byTitle(lv2.words('LV2_DESIGNATION_MEANINGS')))};
`;
}

if (isMain(import.meta.url)) {
  const at = process.argv.indexOf('--contract-dir');
  const text = groupWordsText(at >= 0 ? process.argv[at + 1].split(':').filter(Boolean) : []);
  if (process.argv.includes('--check')) {
    let now = '';
    try { now = readFileSync(OUT_FILE, 'utf8'); } catch { /* absent: stale */ }
    if (now !== text) {
      console.error('group-words-render: tools/group-words.mjs is not what the domains give: run node tools/group-words-render.mjs, then commit');
      process.exit(1);
    }
    console.log('group-words-render: tools/group-words.mjs is what the domains give');
  } else {
    writeFileSync(OUT_FILE, text);
    console.log('group-words-render: wrote tools/group-words.mjs');
  }
}
